        public static void RegisterAdminCommand(ICoreServerAPI sapi, CommandsImplementations ci, CommandArgumentParsers parsers)
        {
            sapi.ChatCommands.Create("eventadmin")
                .RequiresPlayer().RequiresPrivilege(Privilege.controlserver)
                    .BeginSub("start")
                        .WithArgs(parsers.Word("eventCode"))
                        .HandleWith(ci.AdminForceStart)
                        .WithDesc("Force start an event.")
                    .EndSub()
                    .BeginSub("open")
                        .WithArgs(parsers.Word("eventCode"), parsers.OptionalInt("minutes"))
                        .HandleWith(ci.AdminOpenSignup)
                        .WithDesc("Open registration for an event for N minutes (0 = until you start it).")
                    .EndSub()
                    .BeginSub("cancel")
                        .WithArgs(parsers.Word("eventCode"))
                        .HandleWith(ci.AdminCancelSignup)
                        .WithDesc("Close an open registration window without starting the event.")
                    .EndSub()
                    .BeginSub("status")
                        .HandleWith(ci.AdminSignupStatus)
                        .WithDesc("Show open registration windows: who signed up and how long is left.")
                    .EndSub()
                    .BeginSub("stop")
                        .HandleWith(ci.AdminStopAll)
                        .WithDesc("Stop all running events.")
                    .EndSub()
                    .BeginSub("schedule")
                        .BeginSub("on")
                            .HandleWith(ci.AdminScheduleOn)
                            .WithDesc("Enable auto-schedule.")
                        .EndSub()
                        .BeginSub("off")
                            .HandleWith(ci.AdminScheduleOff)
                            .WithDesc("Disable auto-schedule.")
                        .EndSub()
                        .BeginSub("interval")
                            .WithArgs(parsers.Int("minutes"))
                            .HandleWith(ci.AdminScheduleInterval)
                            .WithDesc("Set schedule interval in minutes.")
                        .EndSub()
                    .EndSub()
                    .BeginSub("blacklist")
                        .BeginSub("add")
                            .WithArgs(parsers.Word("player"))
                            .HandleWith(ci.AdminBlacklistAdd)
                            .WithDesc("Ban a player from joining the event queue.")
                        .EndSub()
                        .BeginSub("remove")
                            .WithArgs(parsers.Word("player"))
                            .HandleWith(ci.AdminBlacklistRemove)
                            .WithDesc("Lift a player's event-queue ban.")
                        .EndSub()
                        .BeginSub("list")
                            .HandleWith(ci.AdminBlacklistList)
                            .WithDesc("List queue-blacklisted players.")
                        .EndSub()
                    .EndSub()
                    .BeginSub("ratecap")
                        .BeginSub("show")
                            .WithArgs(parsers.Word("player"))
                            .HandleWith(ci.AdminRateCapShow)
                            .WithDesc("Show a player's remaining reward-slots.")
                        .EndSub()
                        .BeginSub("reset")
                            .WithArgs(parsers.Word("player"))
                            .HandleWith(ci.AdminRateCapReset)
                            .WithDesc("Refill a player's reward rate-cap (clear throttle).")
                        .EndSub()
                    .EndSub();
        }

        public static void RegisterArenaCommand(ICoreServerAPI sapi, CommandsImplementations ci, CommandArgumentParsers parsers)
        {
            sapi.ChatCommands.Create("canreg")
                .RequiresPlayer().RequiresPrivilege(Privilege.chat).WithAlias("cr")
                        .WithArgs(parsers.OptionalWord("eventCode"))
                        .HandleWith(ci.RegPlayer)
                        .WithDesc("Register for an event queue. Usage: /canreg [eventCode]");

            sapi.ChatCommands.Create("canleave")
                .RequiresPlayer().RequiresPrivilege(Privilege.chat)
                        .HandleWith(ci.LeaveQueue)
                        .WithDesc("Leave the event queue.");

            // The root form (watch a match) needs the mod's spectate privilege; "off" does not, so a
            // player whose privilege was revoked while seated can still get out.
            sapi.ChatCommands.Create("canspectate")
                .RequiresPlayer().RequiresPrivilege(Privilege.chat)
                        .BeginSubCommand("off")
                            .HandleWith(ci.LeaveSpectator)
                            .WithDesc("Leave spectator mode after an event.")
                        .EndSubCommand()
                        .BeginSubCommand("list")
                            .RequiresPrivilege(CanEventsPrivileges.Spectate)
                            .HandleWith(ci.ListWatchable)
                            .WithDesc("List the live matches you can watch, with their ids.")
                        .EndSubCommand()
                        .BeginSubCommand("watch")
                            .RequiresPrivilege(CanEventsPrivileges.Spectate)
                            .WithArgs(parsers.OptionalInt("eventId"))
                            .HandleWith(ci.WatchEvent)
                            .WithDesc("Watch a live match. No id = the only one running.")
                        .EndSubCommand()
                        .BeginSubCommand("follow")
                            .RequiresPrivilege(CanEventsPrivileges.Spectate)
                            .WithArgs(parsers.Word("player"))
                            .HandleWith(ci.FollowParticipant)
                            .WithDesc("Move the camera to a participant of the match you are watching.")
                        .EndSubCommand();

            // Duels need no privilege: challenging someone is ordinary play, and every request is
            // validated server-side anyway.
            sapi.ChatCommands.Create("canduel")
                .RequiresPlayer().RequiresPrivilege(Privilege.chat)
                        .WithArgs(parsers.Word("player"), parsers.OptionalWord("stake"))
                        .HandleWith(ci.DuelChallenge)
                        .WithDesc("Challenge a player. Usage: /canduel <player> [code:qty;code:qty] "
                            + "- with a stake it becomes a wager, without one it is a friendly.")
                        .BeginSubCommand("accept")
                            .HandleWith(ci.DuelAccept)
                            .WithDesc("Accept the duel you were challenged to.")
                        .EndSubCommand()
                        .BeginSubCommand("decline")
                            .HandleWith(ci.DuelDecline)
                            .WithDesc("Decline the pending duel, or take back the one you sent.")
                        .EndSubCommand();

            sapi.ChatCommands.Create("canstats")
                .RequiresPlayer().RequiresPrivilege(Privilege.chat)
                        .HandleWith(ci.ShowStats)
                        .WithDesc("Show your event statistics.");
        }
    }
