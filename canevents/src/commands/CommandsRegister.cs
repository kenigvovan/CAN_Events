    public class CommandsRegister
    {
        public static void RegisterCommands(ICoreServerAPI sapi)
        {
            var parsers = sapi.ChatCommands.Parsers;
            CommandsImplementations ci = new CommandsImplementations(sapi);

            // /canparty is owned by the canparty mod; registering it here would throw
            // "Command with such name already exists" when both mods are installed.
            RegisterEventPlaceCommand(sapi, ci, parsers);
            RegisterArenaCommand(sapi, ci, parsers);
            RegisterAdminCommand(sapi, ci, parsers);
            TournamentCommands.Register(sapi, parsers);
        }


        public static void RegisterEventPlaceCommand(ICoreServerAPI sapi, CommandsImplementations ci, CommandArgumentParsers parsers)
        {
            sapi.ChatCommands.Create("caneventplace")
               .RequiresPlayer().RequiresPrivilege(Privilege.chat).RequiresPrivilege(Privilege.controlserver).WithAlias("canep")
                    .BeginSub("new")
                       .HandleWith(ci.NewEventPlace)
                       .WithDesc("Create a new event place.")
                    .EndSub()
                    .BeginSub("delete")
                       .HandleWith(ci.DeleteEventPlace)
                       .WithArgs(parsers.Long("placeId"))
                       .WithDesc("Delete a event place.")
                    .EndSub()
                    .BeginSub("addspawnpoint")
                       .HandleWith(ci.ArenaAddSpawnPoint)
                       .WithAlias("addsp")
                       .WithDesc("Set the first spawn point.")
                    .EndSub()
                    .BeginSub("addtype")
                       .HandleWith(ci.AddPlaceType)
                       .WithDesc("Add type of event place.")
                       .WithArgs(parsers.WordRange("types", PlaceTags.Known))
                    .EndSub()
                    .BeginSub("addname")
                       .HandleWith(ci.SetNameEventPlace)
                       .WithDesc("Set name for place.")
                       .WithArgs(parsers.Word("name"))
                    .EndSub()
                    .BeginSub("mark1")
                       .HandleWith(ci.Mark1)
                       .WithDesc("Set first corner of arena bounds.")
                    .EndSub()
                    .BeginSub("mark2")
                       .HandleWith(ci.Mark2)
                       .WithDesc("Set second corner of arena bounds. Spawn points auto-generated.")
                    .EndSub()
                    .BeginSub("save")
                       .HandleWith(ci.SaveEventPlace)
                       .WithDesc("Save place.")
                    .EndSub()
                    .BeginSub("tpledit")
                       .HandleWith(ci.TplEdit)
                       .WithArgs(parsers.Word("templateCode"))
                       .WithDesc("Place a template arena at your position and start editing its spawn points.")
                    .EndSub()
                    .BeginSub("tpladdsp")
                       .HandleWith(ci.TplAddSp)
                       .WithDesc("Add the current position as a spawn point of the template being edited.")
                    .EndSub()
                    .BeginSub("tplclearsp")
                       .HandleWith(ci.TplClearSp)
                       .WithDesc("Clear all spawn points of the template being edited.")
                    .EndSub()
                    .BeginSub("tpllist")
                       .HandleWith(ci.TplList)
                       .WithDesc("List the current spawn offsets of the template being edited.")
                    .EndSub()
                    .BeginSub("tplsave")
                       .HandleWith(ci.TplSave)
                       .WithDesc("Save the edited template to ModConfig/canevents/arenas/.")
                    .EndSub()
                    .BeginSub("tplcancel")
                       .HandleWith(ci.TplCancel)
                       .WithDesc("Cancel the edit session, restore blocks and remove the test place.")
                    .EndSub()
                    .BeginSub("tplfinish")
                       .HandleWith(ci.TplFinish)
                       .WithDesc("Close the edit session, keep the placed arena.")
                    .EndSub()
                    .BeginSub("cp")
                       .HandleWith(ci.ParkourSetCheckpoint)
                       .WithArgs(parsers.Int("index"))
                       .WithDesc("Mark the block under your feet as a parkour checkpoint with the given index (0-based).")
                    .EndSub()
                    .BeginSub("cpfinish")
                       .HandleWith(ci.ParkourSetFinish)
                       .WithDesc("Mark the block under your feet as the parkour finish.")
                    .EndSub()
                    .BeginSub("cpedit")
                       .HandleWith(ci.ParkourEditCheckpoint)
                       .WithArgs(parsers.Int("index"))
                       .WithDesc("Reassign the index of the marked checkpoint under your feet.")
                    .EndSub()
                    .BeginSub("cplist")
                       .HandleWith(ci.ParkourListCheckpoints)
                       .WithDesc("List all marked checkpoints in the place you're standing in.")
                    .EndSub()
                    .BeginSub("cpremove")
                       .HandleWith(ci.ParkourRemoveCheckpoint)
                       .WithDesc("Remove the marked checkpoint under your feet.")
                    .EndSub()
                    .BeginSub("cplives")
                       .HandleWith(ci.ParkourSetLives)
                       .WithArgs(parsers.Int("lives"))
                       .WithDesc("Set the number of lives for the parkour place you're standing in.")
                    .EndSub()
                    .BeginSub("hgzone")
                       .HandleWith(ci.HgZoneSet)
                       .WithArgs(parsers.Float("radius"))
                       .WithDesc("Set the Hunger Games zone center (block under your feet) and initial radius.")
                    .EndSub()
                    .BeginSub("hgloot")
                       .HandleWith(ci.HgLootAdd)
                       .WithArgs(parsers.OptionalWord("tier"))
                       .WithDesc("Add a loot chest spawn point (block under your feet) with optional tier.")
                    .EndSub()
                    .BeginSub("hglootclear")
                       .HandleWith(ci.HgLootClear)
                       .WithDesc("Clear all Hunger Games loot spots on the place you're standing in.")
                    .EndSub()
