                .RegisterMessageType<MatchHistoryScoreMsg>()
                .RegisterMessageType<RemoveSpawnPointMsg>()
                .RegisterMessageType<RequestLoadoutListMsg>()
                .RegisterMessageType<LoadoutListMsg>()
