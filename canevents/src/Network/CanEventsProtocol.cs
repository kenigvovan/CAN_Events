using Vintagestory.API.Client;
using Vintagestory.API.Common;

namespace canevents.src.Network
{
    /// <summary>
    /// The wire protocol: every message type this mod sends, registered in one place and called from
    /// both sides. Registration order defines each type's id on the wire, and a mismatch produces
    /// silently misread packets rather than a compile error.
    ///
    /// Nested DTOs are registered too. They need not be (RewardTierMsg isn't), but removing them
    /// would shift every later id and break version compatibility.
    /// </summary>
    public static class CanEventsProtocol
    {
        public static void RegisterAll(INetworkChannel channel)
        {
            channel
                .RegisterMessageType<EventStateUpdateMsg>()
                .RegisterMessageType<ScoreboardUpdateMsg>()
                .RegisterMessageType<ScoreEntryMsg>()
                .RegisterMessageType<KillFeedMsg>()
                .RegisterMessageType<EventResultMsg>()
                .RegisterMessageType<EventListMsg>()
                .RegisterMessageType<EventListEntryMsg>()
                .RegisterMessageType<JoinEventRequestMsg>()
                .RegisterMessageType<LeaveEventRequestMsg>()
                .RegisterMessageType<RequestEventListMsg>()
                .RegisterMessageType<RequestPlaceListMsg>()
                .RegisterMessageType<PlaceListMsg>()
                .RegisterMessageType<PlaceListEntryMsg>()
                .RegisterMessageType<CreatePlaceMsg>()
                .RegisterMessageType<AddSpawnPointMsg>()
                .RegisterMessageType<MoveSpawnPointMsg>()
                .RegisterMessageType<SetPlaceBoundsMsg>()
                .RegisterMessageType<TeleportToPlaceMsg>()
                .RegisterMessageType<DeletePlaceMsg>()
                .RegisterMessageType<TogglePlaceMsg>()
                .RegisterMessageType<PlaceOperationResultMsg>()
                .RegisterMessageType<RequestTemplateListMsg>()
                .RegisterMessageType<TemplateListMsg>()
                .RegisterMessageType<TemplateListEntryMsg>()
                .RegisterMessageType<PlaceTemplateMsg>()
                .RegisterMessageType<RemovePlaceWithRestoreMsg>()
                .RegisterMessageType<RequestLeaderboardMsg>()
