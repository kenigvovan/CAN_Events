                .RegisterMessageType<RequestAdminEventListMsg>()
                .RegisterMessageType<AdminEventListMsg>()
                .RegisterMessageType<AdminEventListEntryMsg>()
                .RegisterMessageType<ToggleEventEnabledMsg>()
                .RegisterMessageType<RequestEventRewardConfigMsg>()
                .RegisterMessageType<EventRewardConfigMsg>()
                .RegisterMessageType<RequestRewardLimitsMsg>()
                .RegisterMessageType<RewardLimitsMsg>()
                .RegisterMessageType<AdminActionMsg>()
                .RegisterMessageType<RequestScheduleStateMsg>()
